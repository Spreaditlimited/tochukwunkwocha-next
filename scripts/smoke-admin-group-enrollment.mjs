import assert from "node:assert/strict"
import fs from "node:fs"
import path from "node:path"

const root = process.cwd()
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), "utf8")

const component = read("app/(internal)/internal/(admin)/manual-payments/ExternalGroupAssignmentFields.tsx")
const externalForm = read("app/(internal)/internal/(admin)/manual-payments/AddExternalStudentForm.tsx")
const page = read("app/(internal)/internal/(admin)/manual-payments/page.tsx")
const action = read("app/(internal)/internal/(admin)/manual-payments/actions.ts")
const enrollments = read("lib/admin-enrollments.ts")
const review = read("lib/payments/manual-payment-review.ts")
const family = read("lib/family-enrollment.ts")

assert.match(component, /name="groupLearnersJson"/)
assert.match(component, /Any remaining seats stay available for the parent/)
assert.match(component, /learners\.length >= seatCount/)
assert.match(page, /<AddExternalStudentForm courses=\{courses\} batches=\{allBatches\}/)
assert.doesNotMatch(page, /Default batch \/ Immediate access/)
assert.match(externalForm, /useActionState/)
assert.match(externalForm, /name="sourceType"/)
assert.match(externalForm, /Verified Offline Payment/)
assert.match(externalForm, /placeholder="Select a programme"/)
assert.match(externalForm, /\.filter\(\(batch\) => batch\.courseSlug === courseSlug/)
assert.match(externalForm, /placeholder=\{batchRequiredButUnavailable \? "No active batch available" : "Select a batch"\}/)
assert.match(externalForm, /name="batchKey"[\s\S]*required/)
assert.match(externalForm, /role=\{state\.status === "error" \? "alert" : "status"\}/)
assert.match(externalForm, /data-toast-long="true"/)
assert.match(externalForm, /disabled=\{pending \|\| !courseSlug/)
assert.match(action, /groupLearnersJson/)
assert.match(action, /seatsAvailable/)
assert.match(action, /status: "error"/)
assert.match(action, /return \{[\s\S]*status: "success"/)
assert.match(enrollments, /sourceType !== "manual"/)
assert.match(enrollments, /!immediateAccess && !batchKey/)
assert.match(enrollments, /requireActiveBatch: true/)
assert.match(enrollments, /removeFailedExternalStudentPayment/)
assert.match(enrollments, /No enrollment record was created/)
assert.match(enrollments, /familyEnrollmentEnabledForCourse/)
assert.match(enrollments, /savePendingFamilyChildren/)
assert.match(enrollments, /saved\.length !== groupLearners\.length/)
assert.match(enrollments, /review\.familyProvisioned/)
assert.match(review, /returnApprovedPaymentToPending/)
assert.match(review, /status = 'pending_verification'/)
assert.match(review, /if \(!familyProvisioned\.ok\)/)
assert.match(review, /\[ACTIVATION_EMAIL_FAILED\]/)
assert.match(family, /entry_type, quantity, source_type/)
assert.match(family, /SET seats_consumed = LEAST\(seats_purchased, seats_consumed \+/)

console.log("Admin group enrollment smoke test passed.")
